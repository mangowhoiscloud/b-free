-- Console landing (beginner customer: the platform shows and starts everything). Applied once, after 0005.
--
-- 1. Environments may reference the platform OpenBao layout of D-26 / CLOUD-E2E-CONTRACT 2:
--    ``envs/<environment name>/<secret>`` (e.g. envs/source-aws/chat-db), besides ``tenants/<tenant>/...``.
--    The env name must be the environment's own name. Pilot limitation: ``envs/`` is one namespace for the
--    platform, so two tenants must not use the same environment name (single tenant today).
-- 2. Just-in-time membership from the Access identity: the API calls bravo_jit_principal() for a verified
--    Access email that the configured allowlist (BRAVO_ACCESS_MEMBERS_FILE) names, on that identity's first
--    login only. Never for any other email; never adds roles to an identity that already has a membership.

ALTER TABLE environments DROP CONSTRAINT environments_check;  -- the 0001 secret_ref CHECK (name generated by PostgreSQL)
ALTER TABLE environments ADD CONSTRAINT environments_secret_ref_check CHECK (
  (secret_ref LIKE ('tenants/' || tenant_id || '/%') OR secret_ref LIKE ('envs/' || name || '/%'))
  AND secret_ref !~ '\.\.');

CREATE FUNCTION bravo_jit_principal(p_iss text, p_sub text, p_email text, p_tenant text, p_roles text[])
  RETURNS boolean
  LANGUAGE plpgsql SECURITY DEFINER
  SET search_path = pg_catalog, public
  AS $$
DECLARE
  pid uuid := gen_random_uuid();
BEGIN
  IF coalesce(p_iss, '') = '' OR coalesce(p_sub, '') = '' OR coalesce(p_email, '') !~ '@'
     OR coalesce(p_tenant, '') = '' OR coalesce(cardinality(p_roles), 0) = 0 THEN
    RAISE EXCEPTION 'jit_invalid' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT p_roles <@ ARRAY['viewer', 'operator', 'approver', 'security_approver']::text[] THEN
    RAISE EXCEPTION 'jit_role_unknown' USING ERRCODE = 'check_violation';
  END IF;
  -- Separation of duties (D-18): one person never both requests and approves.
  IF 'operator' = ANY (p_roles) AND p_roles && ARRAY['approver', 'security_approver']::text[] THEN
    RAISE EXCEPTION 'jit_separation_of_duties' USING ERRCODE = 'check_violation';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('bravo-jit:' || p_iss || ':' || p_sub));
  IF EXISTS (SELECT 1 FROM principals p JOIN memberships m ON m.principal_id = p.id
              WHERE p.iss = p_iss AND p.sub = p_sub) THEN
    RETURN false;  -- not a first login: memberships change only through an admin
  END IF;
  PERFORM set_config('app.tenant_id', p_tenant, true);
  INSERT INTO tenants (tenant_id, name) VALUES (p_tenant, p_tenant) ON CONFLICT (tenant_id) DO NOTHING;
  PERFORM set_config('app.principal_id', pid::text, true);
  INSERT INTO principals (id, iss, sub, email) VALUES (pid, p_iss, p_sub, p_email) ON CONFLICT (iss, sub) DO NOTHING;
  SELECT id INTO pid FROM principals WHERE iss = p_iss AND sub = p_sub;
  INSERT INTO memberships (principal_id, tenant_id, role)
    SELECT pid, p_tenant, r FROM unnest(p_roles) AS r ON CONFLICT DO NOTHING;
  RETURN true;
END $$;
REVOKE ALL ON FUNCTION bravo_jit_principal(text, text, text, text, text[]) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION bravo_jit_principal(text, text, text, text, text[]) TO bravo_api, bravo_mcp;
