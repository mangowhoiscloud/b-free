#!/usr/bin/env bash
# Writes deployable Helm values for apps/demo/chart from real sources only:
#   - Terraform outputs (read-only `terraform output`): infra/envs/source-aws, infra/envs/target-onprem
#   - the image reference you pass (registry repository + digest of the image you pushed/imported)
#   - names fixed by deploy/CLOUD-E2E-CONTRACT.md §3, §8 (ns chat, release chat, Secret chat-admin)
# A value that is not available stops the script; nothing is filled in with a guess.
#
# usage: render-values.sh eks    --image-repository R --image-digest sha256:... --public-url U [--out FILE]
#        render-values.sh onprem --image-repository R --image-digest sha256:... --public-url U [--out FILE]
#          onprem without target-onprem outputs: also --s3-endpoint E --s3-bucket B [--s3-region G]
set -Eeuo pipefail
DEMO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO="$(cd "$DEMO/../.." && pwd)"

target="${1:-}"; shift || true
repo="" digest="" public_url="" out="" s3_endpoint="" s3_bucket="" s3_region=""
while [ $# -gt 0 ]; do
  case "$1" in
    --image-repository) repo="$2"; shift 2 ;;
    --image-digest) digest="$2"; shift 2 ;;
    --public-url) public_url="$2"; shift 2 ;;
    --out) out="$2"; shift 2 ;;
    --s3-endpoint) s3_endpoint="$2"; shift 2 ;;
    --s3-bucket) s3_bucket="$2"; shift 2 ;;
    --s3-region) s3_region="$2"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
die() { echo "render-values: $*" >&2; exit 1; }
[ -n "$repo" ] || die "--image-repository is required"
[[ "$digest" =~ ^sha256:[0-9a-f]{64}$ ]] || die "--image-digest must be sha256:<64 hex>"
[[ "$public_url" =~ ^https?:// ]] || die "--public-url is required (the edge hostname phones open)"

tf() {  # tf <env dir> <output>; empty when unavailable
  local dir="$REPO/infra/envs/$1"
  [ -d "$dir/.terraform" ] || return 0
  terraform -chdir="$dir" output -raw "$2" 2>/dev/null || true
}

case "$target" in
  eks)
    bucket="$(tf source-aws attachments_bucket)"; region="$(tf source-aws attachments_bucket_region)"
    secret_arn="$(tf source-aws db_secret_arn)"
    [ -n "$bucket" ] && [ -n "$region" ] && [ -n "$secret_arn" ] \
      || die "infra/envs/source-aws outputs attachments_bucket, attachments_bucket_region, db_secret_arn are not available"
    out="${out:-$DEMO/chart/values-eks.generated.yaml}"
    cat > "$out" <<YAML
# Generated by apps/demo/scripts/render-values.sh eks on $(date -u +%Y-%m-%dT%H:%M:%SZ) from
# terraform output (infra/envs/source-aws) and the image reference given on the command line.
image: {repository: "$repo", digest: "$digest"}
environment: {id: aws, label: AWS, labelJa: AWS}
publicUrl: "$public_url"
db:
  dsnSecret: {name: bravo-demo-db, key: dsn}
  passwordSource: aws-secrets-manager
  secretsManager: {secretId: "$secret_arn", region: "$region"}
attachments:
  storeId: src
  s3: {bucket: "$bucket", region: "$region", addressingStyle: virtual}
serviceAccount:
  name: chat-app
admin:
  tokenSecret: {name: chat-admin, key: token}
YAML
    ;;
  onprem)
    bucket="${s3_bucket:-$(tf target-onprem attachments_bucket)}"
    endpoint="${s3_endpoint:-$(tf target-onprem attachments_endpoint)}"
    region="${s3_region:-$(tf target-onprem attachments_bucket_region)}"
    [ -n "$bucket" ] && [ -n "$endpoint" ] \
      || die "RGW bucket/endpoint not available: no infra/envs/target-onprem outputs; pass --s3-endpoint and --s3-bucket"
    out="${out:-$DEMO/chart/values-onprem.generated.yaml}"
    cat > "$out" <<YAML
# Generated by apps/demo/scripts/render-values.sh onprem on $(date -u +%Y-%m-%dT%H:%M:%SZ).
image: {repository: "$repo", digest: "$digest"}
environment: {id: onprem, label: 온프렘, labelJa: オンプレ}
publicUrl: "$public_url"
db:
  dsnSecret: {name: bravo-demo-db, key: dsn}
  passwordSource: env-file
  passwordSecret: {name: bravo-demo-db, key: password}
attachments:
  storeId: dst
  s3:
    bucket: "$bucket"
    endpointUrl: "$endpoint"
    region: "${region:-us-east-1}"
    addressingStyle: path
    credentialsSecret: {name: bravo-demo-s3}
admin:
  tokenSecret: {name: chat-admin, key: token}
YAML
    ;;
  *) die "first argument must be eks or onprem" ;;
esac
helm lint "$DEMO/chart" -f "$out" >/dev/null || die "helm lint failed for $out"
echo "wrote $out"
