"""Render the relay manifest (ConfigMap with relay.py, Deployment, Service, NetworkPolicy).

    bravo-link render-relay [--namespace chat] [--name dst-db-link] [--image bravo-link-relay] > k8s/reverse-relay.yaml

The image only needs ``python3`` (>= 3.9); relay.py is standard library only and comes from the
ConfigMap. ``k8s/reverse-relay.yaml`` in the repository is this output with the logical image
name ``bravo-link-relay``; ``k8s/kustomization.yaml`` maps it to a digest at deploy time
(``kustomize edit set image bravo-link-relay=<registry>/<repo>@sha256:...``).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

RELAY_SOURCE = Path(__file__).with_name("relay.py")


@dataclass(frozen=True)
class RelaySpec:
    namespace: str = "chat"
    name: str = "dst-db-link"
    image: str = "bravo-link-relay"
    client_port: int = 5432
    agent_port: int = 7070
    uid: int = 10001


def _block(text: str, indent: int) -> str:
    pad = " " * indent
    return "\n".join(pad + line if line else "" for line in text.splitlines())


def render(spec: RelaySpec) -> str:
    labels = {"app.kubernetes.io/name": spec.name, "app.kubernetes.io/component": "reverse-link",
              "app.kubernetes.io/part-of": "bravo-link"}
    lab = "\n".join(f"    {k}: {v}" for k, v in labels.items())
    sel = "\n".join(f"      {k}: {v}" for k, v in labels.items() if k == "app.kubernetes.io/name")
    cmd = json.dumps([
        "python3", "/opt/bravo-link/relay.py",
        "--client-bind", "0.0.0.0", "--client-port", str(spec.client_port),  # noqa: S104 - Service traffic
        "--agent-bind", "127.0.0.1", "--agent-port", str(spec.agent_port),
    ])
    return f"""# Reverse tunnel relay: 임시 링크(D-16 전), tools/link (CLOUD-E2E-CONTRACT.md 7).
# Generated by `bravo-link render-relay`; do not edit by hand (tests compare it with the renderer).
# In-cluster clients (reverse subscription on chat-db, source PgBouncer) connect to Service
# {spec.name}:{spec.client_port}. The agent port {spec.agent_port} listens on 127.0.0.1 inside the pod and is reached
# only by `kubectl port-forward` from the platform laptop.
apiVersion: v1
kind: ConfigMap
metadata:
  name: {spec.name}-relay
  namespace: {spec.namespace}
  labels:
{lab}
data:
  relay.py: |
{_block(RELAY_SOURCE.read_text(encoding="utf-8"), 4)}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: {spec.name}
  namespace: {spec.namespace}
  labels:
{lab}
spec:
  replicas: 1
  strategy:
    type: Recreate
  selector:
    matchLabels:
{sel}
  template:
    metadata:
      labels:
{_block(lab, 4)}
    spec:
      automountServiceAccountToken: false
      securityContext:
        runAsNonRoot: true
        runAsUser: {spec.uid}
        runAsGroup: {spec.uid}
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: relay
          image: {spec.image}
          command: {cmd}
          env:
            - name: PYTHONDONTWRITEBYTECODE
              value: "1"
            - name: PYTHONUNBUFFERED
              value: "1"
          ports:
            - name: client
              containerPort: {spec.client_port}
          readinessProbe:
            tcpSocket:
              port: client
            periodSeconds: 5
          livenessProbe:
            tcpSocket:
              port: client
            periodSeconds: 20
          resources:
            requests:
              cpu: 20m
              memory: 32Mi
            limits:
              memory: 128Mi
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities:
              drop: ["ALL"]
          volumeMounts:
            - name: relay
              mountPath: /opt/bravo-link
              readOnly: true
      volumes:
        - name: relay
          configMap:
            name: {spec.name}-relay
---
apiVersion: v1
kind: Service
metadata:
  name: {spec.name}
  namespace: {spec.namespace}
  labels:
{lab}
spec:
  type: ClusterIP
  selector:
{sel}
  ports:
    - name: client
      port: {spec.client_port}
      targetPort: client
---
# Only pods in this namespace may use the link; the relay itself opens no connections.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: {spec.name}
  namespace: {spec.namespace}
  labels:
{lab}
spec:
  podSelector:
    matchLabels:
{sel}
  policyTypes: ["Ingress", "Egress"]
  ingress:
    - from:
        - podSelector: {{}}
      ports:
        - port: client
  egress: []
"""
